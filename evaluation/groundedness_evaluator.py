import re


# ============================================================
# 1. EXTRACT PAGE CITATIONS
# ============================================================

def extract_citations(answer):

    citations = re.findall(
        r"\[Page\s+(\d+)\]",
        answer,
        re.IGNORECASE
    )

    return [
        int(page)
        for page in citations
    ]


# ============================================================
# 2. CHECK GROUNDEDNESS
# ============================================================

def check_groundedness(answer, retrieved_documents):

    cited_pages = extract_citations(answer)

    retrieved_pages = [
        document.metadata.get("page_number")
        for document in retrieved_documents
    ]

    verified = []
    unsupported = []

    for page in cited_pages:

        if page in retrieved_pages:

            if page not in verified:
                verified.append(page)

        else:

            if page not in unsupported:
                unsupported.append(page)

    # Calculate groundedness score
    total_citations = len(
        set(cited_pages)
    )

    verified_count = len(
        verified
    )

    if total_citations > 0:

        score = (
            verified_count /
            total_citations
        )

    else:

        score = 0.0

    return {
        "cited_pages": cited_pages,
        "retrieved_pages": retrieved_pages,
        "verified_pages": verified,
        "unsupported_pages": unsupported,
        "groundedness_score": score
    }


